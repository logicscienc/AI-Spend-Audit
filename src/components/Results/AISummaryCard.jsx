import React, {useState} from "react";
import {
  Sparkles,
  RefreshCcw,
} from "lucide-react";

export default function AISummaryCard({
  summary,
  loading,
  onRegenerate,
}) {

    const [expanded, setExpanded] = useState(false);

    const WORD_LIMIT = 40;

const getTruncatedText = (text) => {
  const words = text.split(" ");
  if (words.length <= WORD_LIMIT) return text;
  return words.slice(0, WORD_LIMIT).join(" ") + "...";
};

  return (
    <div
      className="
        relative
        overflow-hidden
        rounded-[28px]
        border border-white/10
        bg-white/[0.03]
        backdrop-blur-xl
        p-7
      "
    >

      {/* TOP */}
      <div className="flex items-center justify-between">

        <div className="flex items-center gap-3">

          <div
            className="
              flex items-center justify-center
              w-11 h-11
             
              bg-purple-500/10
              
            "
          >
            <Sparkles
              size={20}
              className="text-purple-300"
            />
          </div>

          <div>

            <p className="text-white font-medium">
              AI-Powered Summary
            </p>

            <p className="text-sm text-white/45">
              Generated by GPT-4.1 Mini
            </p>
          </div>
        </div>

       <button
  onClick={onRegenerate}
  disabled={loading}
  className="
    flex items-center gap-2
    rounded-xl
    border border-white/10
    bg-white/[0.03]
    px-4 py-2
    text-sm text-white/70
    hover:bg-white/[0.05]
    transition-all
    disabled:opacity-50
  "
>
  <RefreshCcw size={15} />
  Regenerate
</button>
      </div>

      {/* CONTENT */}
      <div className="mt-6">

        {loading ? (

          <div className="space-y-3">

            <div className="h-4 w-full rounded bg-white/10 animate-pulse" />
            <div className="h-4 w-[90%] rounded bg-white/10 animate-pulse" />
            <div className="h-4 w-[85%] rounded bg-white/10 animate-pulse" />

          </div>

        ) : (

      <div>
  <p className="text-[15px] leading-8 text-white/75">
    {expanded || !summary
      ? summary
      : getTruncatedText(summary)}
  </p>

  {summary?.split(" ").length > WORD_LIMIT && (
    <button
      onClick={() => setExpanded(!expanded)}
      className="
        mt-3
        text-sm
        text-purple-300
        hover:text-purple-200
        transition
      "
    >
      {expanded ? "Show less" : "Read more"}
    </button>
  )}
</div>
        )}
      </div>

      {/* GLOW */}
      <div
        className="
          absolute
          -bottom-20
          -right-20
          w-72
          h-72
          rounded-full
          bg-purple-500/10
          blur-3xl
          pointer-events-none
        "
      />
    </div>
  );
}